SLO = config.load("slo")
PASSING_TO_16 = {1: 0.5, 4: 1.0, 16: 2.5, 32: 4.0}  # fails the 3 s agent-step SLO at 32
A40_PRICE = 0.9  # arbitrary test price
SLICE_USD = A40_PRICE * 1.0  # matrix.yaml cost.slice_fraction


def test_capacity_rows_and_cost_by_hand(tmp_path):
    write_ladder(tmp_path, PASSING_TO_16, sessions=5, output_tokens=100)
    (row,) = capacity_rows(load_summaries(tmp_path), SLO, "agent-step")
    assert row["capacity"] == 16 and not row["censored"] and row["repeats"] == 2
    # level 16: 20 requests x 100 tokens in a 10 s window = 200 tok/s; 5 sessions = 1800/h
    assert row["output_tok_s"] == pytest.approx(200)
    assert row["sessions_per_hour"] == pytest.approx(1800)
    cost = add_cost(row, SLICE_USD)
    assert cost["usd_per_task"] == pytest.approx(SLICE_USD / 1800)
    assert cost["usd_per_m_tokens"] == pytest.approx(SLICE_USD / (200 * 3600) * 1e6)
    assert add_cost(row, None)["usd_per_task"] is None


def test_plan_matches_hand_calculation(tmp_path, capsys):
    """200 users x 1 session = 200 concurrent; capacity 16 -> ceil(200/16) = 13 slices."""
    write_ladder(tmp_path, PASSING_TO_16)
    code = main(
        [
            "plan",
            "--users",
            "200",
            "--slo",
            "agent-step",
            "--results-dir",
            str(tmp_path),
            "--a40-usd-per-hour",
            "0.9",
        ]
    )
    out = capsys.readouterr().out
    assert code == 0
    assert "200 concurrent agent sessions" in out
    row = next(line for line in out.splitlines() if line.startswith("| vllm"))
    cells = [c.strip() for c in row.strip("|").split("|")]
    assert cells[2] == "16 (n=2)" and cells[3] == "13"
    assert cells[4] == f"{200 / (13 * 16):.0%}"  # 96%
    assert cells[5] == f"{13 * SLICE_USD:.2f}"
    assert cells[7] == f"{SLICE_USD / 1800:.4f}"


def test_plan_prefers_fewest_slices_then_excludes_by_accuracy():
    rows = [
        {"engine": "a", "variant": "big", "capacity": 8, "repeats": 3, "censored": False},
        {"engine": "b", "variant": "small", "capacity": 16, "repeats": 3, "censored": True},
        {"engine": "c", "variant": "dead", "capacity": 0, "repeats": 3},
    ]
    plan = build_plan(rows, 40, 1.0, 0.3)
    assert [o["engine"] for o in plan["options"]] == ["b", "a"]
    assert [o["slices"] for o in plan["options"]] == [3, 5]
    assert plan["excluded"] == [("c", "dead", "no capacity at this SLO")]

    acc = {("a", "big"): 90.0, ("b", "small"): 70.0}
    plan = build_plan(rows, 40, 1.0, 0.3, acc, min_accuracy=80)
    assert [o["engine"] for o in plan["options"]] == ["a"]
    assert any("70.0% < 80" in r for _, _, r in plan["excluded"])


