def test_report_regenerates_tables_and_plots(tmp_path):
    results, reports = tmp_path / "results", tmp_path / "reports"
    write_ladder(results, PASSING_TO_16)
    write_ladder(results, {1: 0.4, 4: 0.9}, workload="chat")
    write_ladder(results, {1: 0.5, 4: 1.2}, engine="sglang")
    append_cell(
        results,
        {
            "engine": "trtllm",
            "variant": "qwen3-8b-int4-awq",
            "status": "not supported",
            "reason": "weights failed to load",
        },
    )
    written = build_report(results, reports, a40_usd_per_hour=A40_PRICE)
    names = {p.name for p in written}
    assert {"results.md", "runs.csv", "latency_qwen3-4b-bf16.png"} <= names
    for p in written:
        assert p.stat().st_size > 0
    md = (reports / "results.md").read_text()
    assert "16 (n=2: 16, 16)" in md  # worst-of-repeats capacity cell
    assert "not supported: weights failed to load" in md  # empty cell kept as a result
    assert "vllm: vllm@sha256:test" in md
    assert "reference not set" not in md  # no quality results yet
    assert len(load_summaries(results)) == 8 + 4 + 4


def test_report_is_reproducible_from_results_alone(tmp_path):
    write_ladder(tmp_path / "r", PASSING_TO_16)
    build_report(tmp_path / "r", tmp_path / "a")
    build_report(tmp_path / "r", tmp_path / "b")
    strip = lambda p: "\n".join(  # noqa: E731
        line for line in (p / "results.md").read_text().splitlines() if "Generated by" not in line
    )
    assert strip(tmp_path / "a") == strip(tmp_path / "b")
    assert (tmp_path / "a" / "runs.csv").read_text() == (tmp_path / "b" / "runs.csv").read_text()


def test_report_without_prices_says_so(tmp_path):
    write_ladder(tmp_path / "r", PASSING_TO_16)
    cfg = tmp_path / "cfg"
    shutil.copytree(config.DEFAULT_CONFIG_DIR, cfg)
    matrix = (cfg / "matrix.yaml").read_text()
    (cfg / "matrix.yaml").write_text(
        re.sub(r"a40_usd_per_hour: [\d.]+", "a40_usd_per_hour: null", matrix)
    )
    build_report(tmp_path / "r", tmp_path / "out", config_dir=cfg)
    assert "no GPU price set" in (tmp_path / "out" / "results.md").read_text()


def test_noise_table_flags_high_variance(tmp_path):
    results = tmp_path / "r"
    # same config, two runs, throughput differs by ~2x
    write_ladder(results, {1: 1.0}, repeats=1, output_tokens=100, dates=["2026-01-01T00:00:00"])
